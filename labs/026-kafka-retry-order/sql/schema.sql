CREATE TABLE attempts (
  case_id VARCHAR(80) NOT NULL, event_id VARCHAR(80) NOT NULL,
  attempts INT NOT NULL, PRIMARY KEY(case_id,event_id)
) ENGINE=InnoDB;
CREATE TABLE completed (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  case_id VARCHAR(80) NOT NULL, seq INT NOT NULL, event_id VARCHAR(80) NOT NULL,
  UNIQUE KEY(case_id,event_id)
) ENGINE=InnoDB;
